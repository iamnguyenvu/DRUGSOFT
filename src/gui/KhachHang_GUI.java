    private void locDuLieuKhachHang() {
        DefaultTableModel model = (DefaultTableModel) tbKhachHang.getModel();
        model.setRowCount(0); // Xóa dữ liệu cũ trong bảng trước khi hiển thị kết quả mới

        List<KhachHang_entity> danhSachKhachHang = khachHangDAO.getTatCaKhachHang();

        // Sắp xếp danh sách khách hàng theo tên riêng (từ cuối cùng) sử dụng Collator để so sánh theo tiếng Việt
        Collator collator = Collator.getInstance(new Locale("vi", "VN")); // Thiết lập Collator cho tiếng Việt

        if (radioAtoZ.isSelected()) {
            danhSachKhachHang.sort((kh1, kh2) -> collator.compare(layTenRieng(kh1.getTenKH()), layTenRieng(kh2.getTenKH())));
        } else if (radioZtoA.isSelected()) {
            danhSachKhachHang.sort((kh1, kh2) -> collator.compare(layTenRieng(kh2.getTenKH()), layTenRieng(kh1.getTenKH())));
        }

        // Lọc danh sách theo giới tính
        if (radioNam.isSelected()) {
            danhSachKhachHang.removeIf(kh -> !kh.getGioiTinh().equalsIgnoreCase("Nam"));
        } else if (radioNu.isSelected()) {
            danhSachKhachHang.removeIf(kh -> !kh.getGioiTinh().equalsIgnoreCase("Nữ"));
        }

        // Hiển thị dữ liệu đã lọc lên bảng
        int stt = 1;
        for (KhachHang_entity kh : danhSachKhachHang) {
            model.addRow(new Object[]{stt++, kh.getTenKH(), kh.getSdtKH(), kh.getDiemThuong(), kh.getGioiTinh()});
        }

        // Hiển thị thông báo nếu không tìm thấy kết quả nào
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Không tìm thấy khách hàng phù hợp với tiêu chí lọc.");
        }
    }



